function deleteDefaultContents(path)
blocks = find_system(path, 'SearchDepth', 1, 'Type', 'Block');
for i = 1:numel(blocks)
    if ~strcmp(blocks{i}, path)
        delete_block(blocks{i});
    end
end
end

function addMatlabFunction(path, position, script)
add_block('simulink/User-Defined Functions/MATLAB Function', path, ...
    'Position', position);
chart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', path);
chart.Script = script;
end

