function [modelFile, model] = Build_TrackShift_F1_HEV_Model(varargin)
% Build_TrackShift_F1_HEV_Model
% Builds a connected native Simulink model for the TrackShift F1-style
% 2026 hybrid-electric power unit demonstrator.
%
% The generated SLX is signal-level rather than Simscape Electrical because
% Simscape Electrical is not installed on the build host. It exposes the
% mechanical/electrical component boundaries explicitly and runs with
% Simulink + Stateflow/MATLAB Function blocks in MATLAB R2025a or Online.
%
% Usage:
%   [file, model] = Build_TrackShift_F1_HEV_Model;
%   [file, model] = Build_TrackShift_F1_HEV_Model('openAfterBuild',true);
%
% The generated model runs two parallel branches from the same telemetry:
%   1) OVERTAKE MODE: handover AI policy may deploy MGU-K power.
%   2) NO OVERTAKE MODE: deployment is disabled; regeneration remains
%      available when braking is permitted.

opts = parseOptions(varargin{:});
mdl = opts.modelName;
modelFile = fullfile(pwd, [mdl '.slx']);

if bdIsLoaded(mdl)
    close_system(mdl, 0);
end
if exist(modelFile, 'file')
    if ~opts.overwrite
        error('Model file already exists: %s', modelFile);
    end
    delete(modelFile);
end

load_system('simulink');
new_system(mdl);
set_param(mdl, 'Location', [40 40 1600 900]);
set_param(mdl, 'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '0.25', 'StopTime', num2str(opts.stopTime_s), ...
    'SaveOutput', 'on', 'OutputSaveName', 'yout', ...
    'SignalLogging', 'on', 'SignalLoggingName', 'logsout', ...
    'ReturnWorkspaceOutputs', 'on');

[t, speed_kph, gap_s, throttle, brake, trackPos_m, gradient_rad] = ...
    makeScenarioSignals(opts.stopTime_s);
ws = get_param(mdl, 'ModelWorkspace');
ws.DataSource = 'Model File';
ws.assignin('TS_SPEED_KPH', [t speed_kph]);
ws.assignin('TS_GAP_S', [t gap_s]);
ws.assignin('TS_THROTTLE', [t throttle]);
ws.assignin('TS_BRAKE', [t brake]);
ws.assignin('TS_TRACK_POS_M', [t trackPos_m]);
ws.assignin('TS_GRADIENT_RAD', [t gradient_rad]);
ws.assignin('TS_ENGINE_CAPACITY_L', 1.6);
ws.assignin('TS_SAMPLE_TIME_S', 0.25);
ws.assignin('TS_HANDOVER_SOURCE', ...
    'handover.rar / handover/export/models (production logistic models)');

buildScenarioInputs([mdl '/Scenario Inputs']);
buildHEVMode([mdl '/OVERTAKE MODE - AI DEPLOY'], true);
buildHEVMode([mdl '/NO OVERTAKE MODE - HOLD + REGEN'], false);
connectScenarioBranches(mdl);
buildTopLevelDashboard(mdl);
buildTopLevelLogging(mdl);

save_system(mdl, modelFile);

% Compile and execute once so the generated model is delivered tested.
set_param(mdl, 'SimulationCommand', 'update');
sim(mdl, 'ReturnWorkspaceOutputs', 'on');
save_system(mdl, modelFile);

model = struct();
model.name = mdl;
model.file = modelFile;
model.sampleTime_s = 0.25;
model.stopTime_s = opts.stopTime_s;
model.modeBranches = ["OVERTAKE MODE - AI DEPLOY"; ...
    "NO OVERTAKE MODE - HOLD + REGEN"];
model.components = ["Scenario Inputs"; "AI Overtake Policy + Rule Gate"; ...
    "Regenerative Braking"; "ICE: 1.6 L V6 Turbo + Fuel Flow"; ...
    "Power Command Governor"; "Inverter + DC Link"; ...
    "MGU-K Electric Machine"; "Energy Store Battery"; ...
    "Turbocharger + Intercooler"; "Fuel System + Injectors"; ...
    "BMS + HV Safety + Thermal Management"; ...
    "Brake-by-Wire + Friction Brakes"; ...
    "8-Speed Gearbox + Differential"; "Aerodynamics + Tyres"; ...
    "Longitudinal Vehicle Dynamics"; "Live Displays and Scopes"];
model.aiSource = 'Embedded handover zone_pass_model, rival_cover_model, deployment_policy, lap_trial_models';
model.validation = 'Model update and fixed-step simulation completed in MATLAB R2025a';

if opts.openAfterBuild
    open_system(mdl);
end
end

function opts = parseOptions(varargin)
p = inputParser;
addParameter(p, 'modelName', 'TrackShift_F1_HEV', @(x) ischar(x) || isstring(x));
addParameter(p, 'stopTime_s', 90, @(x) isnumeric(x) && isscalar(x) && x > 1);
addParameter(p, 'overwrite', true, @(x) islogical(x) || (isnumeric(x) && isscalar(x)));
addParameter(p, 'openAfterBuild', false, @(x) islogical(x) || (isnumeric(x) && isscalar(x)));
parse(p, varargin{:});
opts = p.Results;
opts.modelName = char(opts.modelName);
opts.overwrite = logical(opts.overwrite);
opts.openAfterBuild = logical(opts.openAfterBuild);
end

function [t, speed_kph, gap_s, throttle, brake, trackPos_m, gradient_rad] = ...
    makeScenarioSignals(stopTime_s)
dt = 0.25;
t = (0:dt:stopTime_s)';
speed_kph = 220 + 34*sin(2*pi*t/38) + 16*sin(2*pi*t/17);
speed_kph = speed_kph - 42*exp(-((t-18)/2.4).^2);
speed_kph = speed_kph - 38*exp(-((t-48)/2.8).^2);
speed_kph = speed_kph - 45*exp(-((t-75)/2.7).^2);
speed_kph = min(max(speed_kph, 80), 330);
speed_mps = speed_kph/3.6;
trackPos_m = cumtrapz(t, speed_mps);
lapLength_m = trackPos_m(end);

gap_s = 1.35*ones(size(t));
detectionFractions = [0.19 0.50 0.78];
for i = 1:numel(detectionFractions)
    d0 = detectionFractions(i)*lapLength_m;
    width = 0.10*lapLength_m;
    closeFactor = 1.05;
    if i == 2
        closeFactor = 0.70;
    end
    gap_s = gap_s - closeFactor*exp(-0.5*((trackPos_m-d0)/width).^2);
end
gap_s = min(max(gap_s + 0.03*sin(2*pi*t/9), 0.35), 2.0);

accel = [0; diff(speed_mps)/dt];
throttle = 0.58 + 0.18*sin(2*pi*t/31) + 0.12*(accel > 0);
throttle = min(max(throttle, 0.10), 0.98);
brake = min(max(-accel/7.5, 0), 1);
activationFractions = [0.23 0.54 0.82];
brakingZone = false(size(t));
for i = 1:numel(activationFractions)
    d0 = activationFractions(i)*lapLength_m - 0.08*lapLength_m;
    d1 = activationFractions(i)*lapLength_m + 0.04*lapLength_m;
    brakingZone = brakingZone | (trackPos_m >= d0 & trackPos_m <= d1);
end
brake = max(brake, 0.75*double(brakingZone));
gradient_rad = deg2rad(0.7)*sin(2*pi*trackPos_m/lapLength_m);
end

function buildScenarioInputs(path)
if exist(path, 'file')
    delete_block(path);
end
add_block('simulink/Ports & Subsystems/Subsystem', path, ...
    'Position', [30 130 240 640]);
deleteDefaultContents(path);
signals = { ...
    'Speed_kph', 'TS_SPEED_KPH'; ...
    'Gap_s', 'TS_GAP_S'; ...
    'Throttle', 'TS_THROTTLE'; ...
    'Brake', 'TS_BRAKE'; ...
    'TrackPos_m', 'TS_TRACK_POS_M'; ...
    'Gradient_rad', 'TS_GRADIENT_RAD'};
for i = 1:size(signals, 1)
    y = 30 + (i-1)*75;
    b = [path '/' signals{i,1} '_source'];
    add_block('simulink/Sources/From Workspace', b, ...
        'VariableName', signals{i,2}, 'Position', [25 y 145 y+35]);
    out = [path '/' signals{i,1}];
    add_block('simulink/Ports & Subsystems/Out1', out, ...
        'Port', num2str(i), 'Position', [175 y+7 205 y+23]);
    add_line(path, [signals{i,1} '_source/1'], [signals{i,1} '/1']);
end
set_param(path, 'BackgroundColor', '[0.88 0.93 0.98]');
end

